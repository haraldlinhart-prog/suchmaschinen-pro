// Menu link to the article index on Next.js sites (29.10.2026, christmas.world).
//
// Static sites got their "Ratgeber" link inserted into index.html since 26.09.26, but
// Next.js sites were only flagged 'manual-nextjs' — nobody did the manual part, so new
// blogs (christmas.world/blog) were live with no menu entry pointing at them. Bilingual
// sites also need the link in the visitor's language, pointing at that language's index.
//
// Approach: suchmaschinen.pro writes one small client component next to the site's
// navigation (SuchmaschinenBlogLink) that picks the language section from the current
// path, and inserts it once into the first <nav> it finds. The component file is
// regenerated on every run, so a second language appearing later is picked up without
// touching the navigation again. The JSX insertion is deliberately conservative: when the
// structure is not clearly safe, nothing is changed.

export const NAV_MARKER = 'suchmaschinen.pro:blog-link';
export const COMPONENT_NAME = 'SuchmaschinenBlogLink';

export interface NavSection {
  /** Article language, e.g. 'de' or 'en'. */
  lang: string;
  /** Index URL path, e.g. '/blog/' or '/de/blog/'. */
  href: string;
  /** Menu label in that language. */
  label: string;
  /** Leading path segment that identifies this language section, e.g. 'de'; null = default. */
  prefix: string | null;
}

const LABELS: Record<string, string> = {
  de: 'Ratgeber',
  en: 'Blog',
  fr: 'Blog',
  es: 'Blog',
  it: 'Blog',
  nl: 'Blog',
  th: 'บล็อก',
};

export function blogLabel(lang: string | null | undefined): string {
  return LABELS[(lang || 'de').toLowerCase()] ?? 'Blog';
}

/** '/de/blog/' → 'de'; '/blog/' or '/blog/de/' → null (only a 2-letter first segment counts). */
export function languagePrefix(href: string): string | null {
  const first = href.replace(/^\/+/, '').split('/')[0] || '';
  return /^[a-z]{2}$/i.test(first) ? first.toLowerCase() : null;
}

export function buildSections(entries: Array<{ lang: string; path: string }>): NavSection[] {
  return entries.map(e => {
    const clean = e.path.replace(/^\/+|\/+$/g, '');
    const href = `/${clean}/`;
    return { lang: e.lang, href, label: blogLabel(e.lang), prefix: languagePrefix(href) };
  });
}

/** Source of the generated client component. */
export function buildComponentSource(sections: NavSection[], typescript: boolean): string {
  const data = JSON.stringify(sections.map(s => ({ prefix: s.prefix, href: s.href, label: s.label, lang: s.lang })), null, 2);
  const props = typescript ? '{ className }: { className?: string }' : '{ className }';
  return `'use client';

// Generated by suchmaschinen.pro — menu link to the article index in the visitor's language.
// This file is rewritten automatically; edit the sections in suchmaschinen.pro, not here.
import { usePathname } from 'next/navigation';

const SECTIONS = ${data};

export default function ${COMPONENT_NAME}(${props}) {
  const pathname = usePathname() || '/';
  const first = pathname.split('/')[1] || '';
  // Language section of the current page; pages of a language without articles yet get no link.
  const section =
    SECTIONS.find((s) => s.prefix !== null && s.prefix === first) ??
    SECTIONS.find((s) => s.prefix === null && !SECTIONS.some((o) => o.prefix === first));
  if (!section) return null;
  return (
    <a href={section.href} hrefLang={section.lang} className={className}>
      {section.label}
    </a>
  );
}
`;
}

/** True if the navigation already links to the article index (by hand or by us). */
export function navLinksToBlog(nav: string, publishPath: string): boolean {
  if (nav.includes(COMPONENT_NAME) || nav.includes(NAV_MARKER)) return true;
  const p = publishPath.replace(/^\/+|\/+$/g, '').replace(/[.*+?^${}()|[\]\\]/g, '\\$&');
  return new RegExp(`["'\`](https?://[^"'\`]*)?/?${p}/?["'\`#?]`, 'i').test(nav);
}

function braceDepth(s: string): number {
  let d = 0;
  for (const ch of s) {
    if (ch === '{') d++;
    else if (ch === '}') d--;
  }
  return d;
}

export type InsertResult =
  | { ok: true; source: string }
  | { ok: false; reason: 'no-nav' | 'present' | 'unsafe' };

/**
 * Inserts the component into the first JSX <nav> of a source file: after the first plain
 * <Link>/<a> (position 2, like the static sites) when that link is a direct child of the
 * nav; otherwise just before </nav>. Adds the import after the last import line.
 */
export function insertNavComponent(source: string, publishPath: string, importPath: string): InsertResult {
  const open = /<nav\b[^>]*>/.exec(source);
  if (!open) return { ok: false, reason: 'no-nav' };
  const navStart = open.index;
  const innerStart = navStart + open[0].length;
  const close = source.indexOf('</nav>', innerStart);
  if (close === -1) return { ok: false, reason: 'unsafe' };
  if (source.indexOf('<nav', innerStart) !== -1 && source.indexOf('<nav', innerStart) < close) return { ok: false, reason: 'unsafe' };
  const nav = source.slice(navStart, close + 6);
  if (navLinksToBlog(nav, publishPath)) return { ok: false, reason: 'present' };
  if (braceDepth(source.slice(innerStart, close)) !== 0) return { ok: false, reason: 'unsafe' };

  const inner = source.slice(innerStart, close);
  // First plain link: <Link ...>…</Link> or <a ...>…</a>, not logo/brand/cta/button/language.
  const linkRe = /<(Link|a)\b([^>]*)>[\s\S]*?<\/\1>/g;
  let insertAt = -1;
  let className = '';
  for (let m = linkRe.exec(inner); m; m = linkRe.exec(inner)) {
    const attrs = m[2];
    if (/className=["'][^"']*(logo|brand|cta|btn|button|lang)/i.test(attrs)) continue;
    if (/hrefLang=/i.test(attrs)) continue;
    // Only a direct child: no open expression ({links.map(…)}) before it.
    if (braceDepth(inner.slice(0, m.index)) !== 0) break;
    insertAt = innerStart + m.index + m[0].length;
    className = /className=["']([^"']+)["']/.exec(attrs)?.[1] ?? '';
    break;
  }
  const closeLineStart = source.lastIndexOf('\n', close - 1);
  const indent = (/^[ \t]*/.exec(source.slice(closeLineStart + 1, close))?.[0] ?? '') + '  ';
  const element = `{/* ${NAV_MARKER} */}\n${indent}<${COMPONENT_NAME}${className ? ` className="${className}"` : ''} />`;

  let out: string;
  if (insertAt !== -1) {
    out = `${source.slice(0, insertAt)}\n${indent}${element}${source.slice(insertAt)}`;
  } else {
    // Before </nav>, on its own line.
    const lineStart = source.lastIndexOf('\n', close - 1);
    const onOwnLine = /^\s*$/.test(source.slice(lineStart + 1, close));
    out = onOwnLine
      ? `${source.slice(0, lineStart)}\n${indent}${element}${source.slice(lineStart)}`
      : `${source.slice(0, close)}${element}${source.slice(close)}`;
  }

  // Import after the last top-level import statement ('use client' stays first).
  const importLine = `import ${COMPONENT_NAME} from '${importPath}';`;
  const importRe = /^import\b[\s\S]*?from\s+['"][^'"]+['"];?[ \t]*$/gm;
  let lastEnd = -1;
  for (let m = importRe.exec(out); m; m = importRe.exec(out)) lastEnd = m.index + m[0].length;
  if (lastEnd !== -1) {
    out = `${out.slice(0, lastEnd)}\n${importLine}${out.slice(lastEnd)}`;
  } else {
    const directive = /^(['"]use (client|server)['"];?[ \t]*\n)/.exec(out);
    out = directive ? `${directive[1]}${importLine}\n${out.slice(directive[1].length)}` : `${importLine}\n${out}`;
  }

  // Sanity: same number of <nav>/</nav>, braces still balanced inside the nav.
  const o2 = out.indexOf('</nav>', out.search(/<nav\b/));
  if (braceDepth(out.slice(out.search(/<nav\b/), o2)) !== 0) return { ok: false, reason: 'unsafe' };
  if ((out.match(/<nav\b/g) || []).length !== (source.match(/<nav\b/g) || []).length) return { ok: false, reason: 'unsafe' };
  return { ok: true, source: out };
}

/** Order in which candidate files are checked for the site navigation. */
export function rankNavCandidates(paths: string[]): string[] {
  const src = paths.filter(p =>
    /\.(tsx|jsx)$/.test(p) &&
    !/(^|\/)(node_modules|\.next|public|out|dist)\//.test(p) &&
    !/\.(test|spec|stories)\./.test(p) &&
    /^(src\/)?(app|components|lib|layouts?|ui|pages)\//.test(p)
  );
  const score = (p: string) => {
    const name = p.split('/').pop()!.toLowerCase();
    if (/(header|navbar|nav|navigation|menu)/.test(name)) return 0;
    if (/(shell|sitechrome|chrome|frame)/.test(name)) return 1;
    if (/layout/.test(name)) return 2;
    if (/(site|page)/.test(name)) return 3;
    return 4;
  };
  return src.sort((a, b) => score(a) - score(b) || a.length - b.length);
}

export function relativeImport(navFile: string, componentFile: string): string {
  const from = navFile.split('/').slice(0, -1);
  const to = componentFile.replace(/\.(tsx|jsx)$/, '').split('/');
  let i = 0;
  while (i < from.length && i < to.length - 1 && from[i] === to[i]) i++;
  const up = from.length - i;
  const rest = to.slice(i).join('/');
  return up === 0 ? `./${rest}` : `${'../'.repeat(up)}${rest}`;
}
